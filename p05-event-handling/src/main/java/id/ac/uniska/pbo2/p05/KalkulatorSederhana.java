private void hitung(char operator) {
    try {
        double angka1 = Double.parseDouble(angka1Field.getText().trim());
        double angka2 = Double.parseDouble(angka2Field.getText().trim());
        double hasil;

        switch (operator) {
            case '+':
                hasil = angka1 + angka2;
                break;
            case '-':
                hasil = angka1 - angka2;
                break;
            case 'x':
                hasil = angka1 * angka2;
                break;
            case '/':
                if (angka2 == 0) {
                    hasilLabel.setText("Tidak bisa dibagi 0");
                    return;
                }
                hasil = angka1 / angka2;
                break;
            default:
                return;
        }

        hasilLabel.setText("Hasil: " + rapikan(hasil));

    } catch (NumberFormatException e) {
        hasilLabel.setText("Masukkan dua angka yang valid");
    }
}

private void hapus(java.awt.event.ActionEvent e) {
    angka1Field.setText("");
    angka2Field.setText("");
    hasilLabel.setText("Hasil: 0");
    angka1Field.requestFocusInWindow();
}

private static String rapikan(double nilai) {
    if (nilai == Math.rint(nilai)) {
        return String.valueOf((long) nilai);
    }
    return String.valueOf(nilai);
}
